export default function StatsSection() {
  const sectionRef = useRef<HTMLElement>(null)

  useEffect(() => {
    const el = sectionRef.current
    if (!el) return
    const observer = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) {
          el.querySelectorAll('.stat-item').forEach((item, i) => {
            setTimeout(() => {
              (item as HTMLElement).style.opacity = '1';
              (item as HTMLElement).style.transform = 'translateY(0)'
            }, i * 100)
          })
        }
      },
      { threshold: 0.2 }
    )
    observer.observe(el)
    return () => observer.disconnect()
  }, [])

  return (
    <section ref={sectionRef} className="relative bg-[#0a0a0f] py-16 overflow-hidden">
      <div className="absolute inset-0 bg-radial-primary" />
      <div className="relative max-w-[87.5rem] mx-auto px-6">
        <div className="grid grid-cols-2 md:grid-cols-4 gap-6 md:gap-8">
          {stats.map((stat) => (
            <div
              key={stat.label}
              className="stat-item flex flex-col items-center text-center p-6 rounded-2xl bg-[#13111a]/60 border border-[#64189D]/10 hover:border-[#64189D]/25 transition-all duration-300"
              style={{ opacity: 0, transform: 'translateY(20px)', transition: 'all 0.5s ease-out' }}
            >
              <div className="w-12 h-12 rounded-xl bg-gradient-to-br from-[#64189D]/20 to-[#A855F7]/10 flex items-center justify-center text-[#A855F7] mb-4">
                {stat.icon}
              </div>
              <span className="text-white font-black text-3xl md:text-4xl">{stat.value}</span>
              <span className="text-white/40 text-sm font-medium mt-1">{stat.label}</span>
            </div>
          ))}
        </div>
      </div>
    </section>
  )
}
